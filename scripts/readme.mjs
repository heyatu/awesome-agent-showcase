import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { groupByFirstPurpose, linkState, loadCollection } from './collection.mjs';
import { marketUrl, quotedRights } from './entry.mjs';

export const PLACEMENTS = ['market-hero', 'market-grid', 'market-category'];
export const BLOCK_START = '<!-- collection:start -->';
export const BLOCK_END = '<!-- collection:end -->';

export function trackedUrl(id, placement) {
  if (!PLACEMENTS.includes(placement)) throw new Error(`Unknown placement ${placement}`);
  return `${marketUrl(id)}?utm_source=github&utm_medium=readme&utm_campaign=${placement}`;
}

const HTML_ENTITIES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' };
const escapeHtml = (text) => text.replace(/[&<>"]/g, (character) => HTML_ENTITIES[character]);
const escapeMarkdown = (text) => text.replace(/[\\`*_{}[\]()<>#+\-.!|~&]/g, '\\$&');
const CARDS_PER_ROW = 2;

function coverPaths(entry) {
  if (!entry.cover) return null;
  const { motion, still } = entry.cover;
  return /\.(gif|webp)$/.test(motion) ? { motion, still } : { motion: null, still };
}

function renderCover(entry, href) {
  const paths = coverPaths(entry);
  if (!paths) return null;
  const alt = escapeHtml(entry.title);
  const src = (path) => `entries/${entry.id}/${path}`;
  const image = paths.motion
    ? `<picture><source media="(prefers-reduced-motion: reduce)" srcset="${src(paths.still)}"><img src="${src(paths.motion)}" alt="${alt}" width="100%"></picture>`
    : `<img src="${src(paths.still)}" alt="${alt}" width="100%">`;
  return href ? `<a href="${escapeHtml(href)}">${image}</a>` : image;
}

function renderBrief(brief) {
  return `<details>\n<summary>Brief</summary>\n\n\`\`\`text\n${brief}\n\`\`\`\n\n</details>`;
}

function renderMeta(entry) {
  const cover = coverPaths(entry);
  const quoted = cover && (quotedRights(entry, cover.motion) ?? quotedRights(entry, cover.still));
  const prompt = entry.prompts?.find(({ choice }) => choice === entry.action?.prompt);
  return [
    entry.collection === 'editors-pick' && "★ Editor's Pick",
    quoted && `via <a href="${escapeHtml(quoted.sourceUrl)}">@${escapeHtml(quoted.holder)}</a>`,
    prompt?.status === 'tested' && 'Tested in Hey Atu',
    ...(entry.tags ?? []).map((tag) => escapeHtml([tag.name, tag.version].filter(Boolean).join(' '))),
  ].filter(Boolean).join(' · ');
}

function runLabel(entry) {
  if (!entry.action) return 'View on Hey Atu Market →';
  const prompt = entry.prompts.find(({ choice }) => choice === entry.action.prompt);
  return prompt.status === 'tested' ? 'Run the tested version in Hey Atu →' : 'Try it in Hey Atu →';
}

function renderCard(entry, deployments) {
  const linked = linkState(entry, deployments) !== 'none';
  const gridUrl = linked ? trackedUrl(entry.id, 'market-grid') : null;
  const title = escapeHtml(entry.title);
  const meta = renderMeta(entry);
  const parts = [
    renderCover(entry, gridUrl),
    `<p><strong>${gridUrl ? `<a href="${escapeHtml(gridUrl)}">${title}</a>` : title}</strong><br>${escapeHtml(entry.summary)}</p>`,
    meta && `<p>${meta}</p>`,
    entry.brief && renderBrief(entry.brief),
    linked && `<p><a href="${escapeHtml(trackedUrl(entry.id, 'market-category'))}">${runLabel(entry)}</a></p>`,
  ];
  return parts.filter(Boolean).join('\n\n');
}

function renderTable(cards) {
  const rows = [];
  for (let start = 0; start < cards.length; start += CARDS_PER_ROW) {
    const cells = cards.slice(start, start + CARDS_PER_ROW);
    while (cells.length < CARDS_PER_ROW) cells.push('');
    rows.push(`<tr>\n${cells.map((cell) => `<td width="${100 / CARDS_PER_ROW}%" valign="top">\n\n${cell}${cell ? '\n\n' : ''}</td>`).join('\n')}\n</tr>`);
  }
  return `<table>\n${rows.join('\n')}\n</table>`;
}

export function renderBlock({ purposes, entries, deployments }) {
  const { total, groups } = groupByFirstPurpose(purposes, entries);
  const lines = [BLOCK_START, '<!-- Generated by scripts/readme.mjs. Edit entries or tags, then run it again. -->', ''];
  if (total === 0) lines.push('No items are listed yet.', '');
  const picks = [...new Map(entries.map((entry) => [entry.id, entry])).values()]
    .filter((entry) => entry.collection === 'editors-pick').sort((a, b) => (a.id < b.id ? -1 : 1));
  if (picks.length > 0) {
    lines.push(`### ★ Editor's Picks (${picks.length})`, '', "Aesthetic Remake: we rebuild projects we liked with one prompt.", '', renderTable(picks.map((entry) => renderCard(entry, deployments))), '');
  }
  for (const { label, entries: members } of groups.filter(({ entries: members }) => members.length > 0)) {
    lines.push(`### ${escapeMarkdown(label)} (${members.length})`, '', renderTable(members.map((entry) => renderCard(entry, deployments))), '');
  }
  lines.push(BLOCK_END);
  return lines.join('\n');
}

export function replaceBlock(readme, block) {
  const start = readme.indexOf(BLOCK_START);
  const end = readme.indexOf(BLOCK_END);
  if (start === -1 || end < start) throw new Error('README.md has no collection block markers');
  return readme.slice(0, start) + block + readme.slice(end + BLOCK_END.length);
}

function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const collection = loadCollection(root);
  if (collection.errors.length > 0) {
    console.error(collection.errors.join('\n'));
    process.exit(1);
  }
  const path = join(root, 'README.md');
  const current = readFileSync(path, 'utf8');
  const next = replaceBlock(current, renderBlock(collection));
  if (process.argv.includes('--check')) {
    if (next !== current) {
      console.error('README.md collection block is stale. Run: node scripts/readme.mjs');
      process.exit(1);
    }
  } else if (next !== current) writeFileSync(path, next);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
